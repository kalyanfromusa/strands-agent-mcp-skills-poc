"""Pin each container image's Python dependencies to the exact versions in uv.lock, with hashes.

    uv run python scripts/pin_requirements.py            # rewrite the *.lock.txt files
    uv run python scripts/pin_requirements.py --check    # exit 1 if a lock file is out of date (CI)

What this file does
    Each image lists its direct dependencies, with version ranges, in a small `requirements.in`
    (agent/requirements.in, mcp_servers/support_mcp/requirements.in). This script turns each one into a
    `requirements.lock.txt`: every package the image needs, each pinned to one exact version, with the
    download's SHA-256 hashes. The Dockerfiles install from the lock file with `--require-hashes`, so two
    builds of the same commit get byte-identical packages, and a tampered download is refused.

Where it fits
    Run it after changing a requirements.in or after `uv lock --upgrade`. tests/test_pinned_requirements.py
    checks offline that every pinned version matches uv.lock, so the images and local development
    (`uv run`) always use the same versions. The orders and role-mapper Lambdas need no extra packages
    (boto3 comes with the Lambda base image), so they have no lock file.

Step by step
    1. Export the whole project's resolved versions from uv.lock as a constraints file (no hashes).
    2. For each image, run `uv pip compile requirements.in` for Linux arm64 / Python 3.12 (the platform
       AgentCore Runtime uses), constrained to those versions, with hashes.
    3. Write the result as requirements.lock.txt (or, with --check, compare it to the existing file).

Key terms
    Lock file: a list of exact package versions, so installs are repeatable.
    Constraint: "if you install this package, use exactly this version", without forcing it in.
    Hash: a fingerprint of the package file; pip refuses a download whose fingerprint differs.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Image => its requirements.in. The lock file is written next to it.
IMAGES = {
    "agent": ROOT / "agent" / "requirements.in",
    "support_mcp": ROOT / "mcp_servers" / "support_mcp" / "requirements.in",
}

# The platform of the AgentCore Runtime microVMs (and of the GitHub arm64 runners that build the images).
PLATFORM = ["--python-platform", "aarch64-manylinux2014", "--python-version", "3.12"]


def lock_path(req_in: Path) -> Path:
    """agent/requirements.in -> agent/requirements.lock.txt"""
    return req_in.with_name("requirements.lock.txt")


def run(cmd: list[str]) -> str:
    """Run a command from the repo root and return its stdout; stop with its stderr on failure."""
    proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"command failed: {' '.join(cmd)}\n{proc.stderr}")
    return proc.stdout


def compile_lock(req_in: Path, constraints: Path) -> str:
    """Step 2: resolve one image's requirements against uv.lock's versions, for linux/arm64, with hashes."""
    rel = req_in.relative_to(ROOT).as_posix()
    out = run([
        "uv", "pip", "compile", rel,
        "--constraint", str(constraints),
        *PLATFORM,
        "--generate-hashes",
        "--no-header",
        "--no-annotate",  # no "# via ..." comments: they embed the temporary constraints path
        "--quiet",
    ])
    header = (
        f"# Generated by scripts/pin_requirements.py from {rel} and uv.lock. Do not edit by hand.\n"
        "# Linux arm64, Python 3.12. Install with: uv pip install --require-hashes -r requirements.lock.txt\n"
    )
    return header + out.replace("\r\n", "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a lock file differs instead of writing it")
    args = parser.parse_args()

    # Step 1: every resolved version of the project, as constraints.
    exported = run(["uv", "export", "--frozen", "--no-hashes", "--no-dev", "--no-emit-project", "--quiet"])
    stale = []
    with tempfile.TemporaryDirectory() as tmp:
        constraints = Path(tmp) / "constraints.txt"
        constraints.write_text(exported, encoding="utf-8")

        # Steps 2 and 3, per image.
        for name, req_in in IMAGES.items():
            wanted = compile_lock(req_in, constraints)
            target = lock_path(req_in)
            current = target.read_text(encoding="utf-8") if target.exists() else ""
            if args.check:
                if current != wanted:
                    stale.append(target.relative_to(ROOT).as_posix())
            else:
                target.write_text(wanted, encoding="utf-8", newline="\n")
                print(f"wrote {target.relative_to(ROOT).as_posix()} ({wanted.count('==')} pinned packages) for {name}")

    if stale:
        print("out of date (run scripts/pin_requirements.py):", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
